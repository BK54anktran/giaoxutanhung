                    8 tháng Giêng thì Lễ Chúa Giêsu Chịu Phép Rửa sẽ được cử hành vào Chúa nhật của tuần sau đó. – Nếu
                    không thì ngày thứ Hai sau Chúa nhật Lễ Hiển Linh sẽ là ngày cử hành Lễ Chúa Giêsu Chịu Phép Rửa. Lễ
                    Chúa Giêsu Chịu Phép Rửa đánh dấu cho ngày cuối cùng của Mùa Giáng Sinh. Mùa Giáng Sinh bắt đầu từ
                    Lễ Giáng Sinh đến Lễ Chúa Giêsu Chịu Phép Rửa. Hang đá được dẹp đi sau Lễ Chúa Giêsu Chịu Phép Rửa.
