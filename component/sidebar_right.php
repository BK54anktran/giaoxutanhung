                    Cách ăn chay và kiêng thịt Thứ tư Lễ Tro là ngày khởi đầu cho Mùa Chay. Mùa này kéo dài đúng bốn
                    mươi ngày trước Lễ Phục Sinh. Chúng ta được xức tro trên đầu với ý niệm “con người xuất thân từ tro
                    bụi và cũng sẽ trở về tro bụi”. Loại tro này được lấy từ việc đốt lá dùng trong Chúa nhật Lễ Lá năm
                    trước.</p>
