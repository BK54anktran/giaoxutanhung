                    Chúa Giêsu. Lễ diễn ra vào buổi tối, đánh dấu sự bắt đầu của Tam Nhật Thánh: một thời kỳ ba ngày,
                    liên tưởng đến ba ngày kể từ sự chết đến sống lại của Chúa Giêsu. Tam Nhật Thánh (3 ngày trước ngày
